    |> Ash.Query.for_read(
      :for_workspace,
      %{workspace_id: scope.current_workspace.id},
      scope: scope
    )
    |> Ash.read_one()
    |> case do
      {:ok, nil} -> {:error, :not_found}
      result -> result
    end
  end

  @doc "Spec KLM6: saves the official header lines and the signature and stamp paths (head only)."
  def update_official_header(%Scope{} = scope, attrs) do
    with {:ok, profile} <- fetch_school_profile(scope) do
      profile
      |> Ash.Changeset.for_update(:update_official_header, attrs, scope: scope)
      |> Ash.update()
    end
  end

  def can_edit_official_header?(%Scope{} = scope) do
    case fetch_school_profile(scope) do
      {:ok, profile} -> Ash.can?({profile, :update_official_header}, scope)
      _ -> false
    end
  end

  def list_unverified_schools(%Scope{} = scope) do
    SchoolProfile |> Ash.Query.for_read(:unverified, %{}, scope: scope) |> Ash.read!()
  end

  # --- School memberships --------------------------------------------------

  def fetch_school_membership(%Scope{} = scope, %User{id: user_id}) do
    SchoolMembership
    |> Ash.Query.for_read(:for_workspace_and_user, %{user_id: user_id}, scope: scope)
    |> Ash.read_one()
    |> case do
      {:ok, nil} -> {:error, :not_a_member}
      {:ok, m} -> {:ok, m}
      error -> error
    end
  end

  @doc """
  A user's display name by id, whoever they are (a member, or the operator who acted
  as one); nil when unknown. Internal read: names only, never the account.
  """
  def user_name(nil), do: nil
  def user_name(id), do: Map.get(user_names([id]), id)

  @doc "`%{user id => display name}` for `ids`, in one read (see `user_name/1`)."
  def user_names([]), do: %{}

  def user_names(ids) do
    User
    |> Ash.Query.filter(id in ^Enum.uniq(ids))
    |> Ash.read!(authorize?: false)
    |> Map.new(&{&1.id, User.display_name(&1)})
  end

  def list_members(%Scope{} = scope) do
    SchoolMembership
    |> Ash.Query.for_read(:active_for_workspace, %{}, scope: scope)
    |> Ash.read!()
  end

  @doc """
  The operator journal, newest first (operator console spec §4). Operator only.
  Options: `workspace_id`, `action`, `limit` (default 50), `offset` (default 0).
  """
  def list_audit_events(%Scope{} = scope, opts) do
    TeacherAssistant.Accounts.AuditEvent
    |> Ash.Query.for_read(:read, %{}, scope: scope)
    |> filter_audit(:workspace_id, opts[:workspace_id])
    |> filter_audit(:action, opts[:action])
    |> Ash.Query.sort(inserted_at: :desc, id: :desc)
    |> Ash.Query.limit(opts[:limit] || 50)
    |> Ash.Query.offset(opts[:offset] || 0)
    |> Ash.Query.load([:actor, :target_user, :workspace])
    |> Ash.read!()
  end

  defp filter_audit(query, _field, nil), do: query
  defp filter_audit(query, :workspace_id, id), do: Ash.Query.filter(query, workspace_id == ^id)
  defp filter_audit(query, :action, action), do: Ash.Query.filter(query, action == ^action)

  @doc "Active members' display names by user id, to name who issued or recorded something."
  def member_names(%Scope{} = scope) do
    Map.new(list_members(scope), &{&1.user_id, &1.user && User.display_name(&1.user)})
  end

  def update_member_roles(%Scope{} = scope, %SchoolMembership{} = m, roles) do
    with_head_lock(scope, fn ->
      if removing_last_head?(scope, m, roles) do
        {:error, :last_head}
      else
        m |> Ash.Changeset.for_update(:update, %{roles: roles}, scope: scope) |> Ash.update()
      end
    end)
  end

  def update_member_status(%Scope{} = scope, %SchoolMembership{} = m, status) do
    m
    |> Ash.Changeset.for_update(:update, %{status: status}, scope: scope)
    |> Ash.update()
  end

  def deactivate_member(%Scope{} = scope, %SchoolMembership{} = m) do
    with_head_lock(scope, fn ->
      if :head in m.roles and last_head?(scope, m) do
        {:error, :last_head}
      else
        m |> Ash.Changeset.for_update(:deactivate, %{}, scope: scope) |> Ash.update()
      end
    end)
  end

  # One change that could remove a head at a time per school: two heads removing
  # each other at once would both see the other still there, leaving no head.
  # The second waits here, then counts the heads the first left.
  defp with_head_lock(%Scope{current_workspace: %{id: ws_id}}, fun) do
    TeacherAssistant.Repo.transaction(fn ->
      TeacherAssistant.Repo.query!("SELECT pg_advisory_xact_lock(hashtext($1))", [
        "school_heads:" <> ws_id
      ])

      case fun.() do
        {:ok, result} -> result
        {:error, error} -> TeacherAssistant.Repo.rollback(error)
      end
    end)
    |> transaction_error()
  end

  # A refused Ash write inside `Repo.transaction` rolls it back with its bare error
  # (e.g. a policy error); give callers the class they match on (`%Forbidden{}`).
  # Our own reasons (`:last_head`, `:email_not_sent`) are atoms and pass through.
  defp transaction_error({:error, error}) when not is_atom(error),
    do: {:error, Ash.Error.to_error_class(error)}

  defp transaction_error(result), do: result

  defp removing_last_head?(%Scope{} = scope, %SchoolMembership{} = m, new_roles) do
    :head in m.roles and :head not in new_roles and last_head?(scope, m)
  end

  # The guard itself lives here (rather than as a resource validation) so
  # callers keep getting the bare `{:error, :last_head}` atom instead of an
  # `%Ash.Error.Invalid{}` — the `other_active_heads` aggregate on
  # `SchoolMembership` does the actual counting.
  defp last_head?(%Scope{} = scope, %SchoolMembership{} = m) do
    m |> Ash.load!(:other_active_heads, scope: scope) |> Map.fetch!(:other_active_heads) == 0
  end

  # --- School invitations --------------------------------------------------

  def invite_member(%Scope{} = scope, %{} = attrs) do
    school = scope.current_workspace
    email = attrs[:email] || attrs["email"]
    roles = attrs[:roles] || attrs["roles"] || [:teacher]
    membership_status = attrs[:membership_status] || attrs["membership_status"]

    with false <- active_member_email?(scope, email),
         {:ok, invitation} <-
           TeacherAssistant.Repo.transaction(fn ->
             scope
             |> create_and_send_invitation(school, %{
               email: email,
               roles: roles,
               membership_status: membership_status
             })
             |> case do
               {:ok, invitation} -> invitation
               {:error, error} -> TeacherAssistant.Repo.rollback(error)
             end
           end)
           |> transaction_error() do
      {:ok, invitation}
    else
      true -> {:error, :already_member}
      {:error, error} -> {:error, error}
    end
  end

  # The invitation is kept only once its email went out: a refused send rolls it
  # back (`{:error, :email_not_sent}`), so the head is never told it was sent.
  defp create_and_send_invitation(scope, school, attrs) do
    with {:ok, invitation} <-
           SchoolInvitation
           |> Ash.Changeset.for_create(
             :create,
             Map.merge(attrs, %{
               invited_by_user_id: scope.current_user && scope.current_user.id,
               token: gen_token(),
               expires_at:
                 DateTime.add(DateTime.utc_now(), 14, :day) |> DateTime.truncate(:second)
             }),
             scope: scope
           )
           |> Ash.create() do
      case SendSchoolInvitationEmail.send(invitation.email, school.name, invitation.token) do
        :ok -> {:ok, invitation}
        {:error, _reason} -> {:error, :email_not_sent}
      end
    end
  end

  def fetch_invitation_by_token(token) do
    SchoolInvitation
    |> Ash.Query.for_read(:by_token, %{token: token})
    |> Ash.read_one()
    |> case do
      {:ok, nil} ->
        {:error, :not_found}

      # The token is the credential (spec §4.2): its bearer may see which
      # school invited them, before they are a member or signed in.
      {:ok, inv} ->
        Ash.load(inv, :workspace, authorize?: false)

      error ->
        error
    end
  end

  def list_pending_invitations(%Scope{} = scope) do
    SchoolInvitation
    |> Ash.Query.for_read(:pending_for_workspace, %{}, scope: scope)
    |> Ash.read!()
  end

  def accept_invitation(%Scope{current_user: %User{} = user} = scope, token) do
    with {:ok, inv} <- fetch_invitation_by_token(token),
         :ok <- check_acceptable(inv),
         :ok <- check_email(inv, user),
         {:ok, _} <-
           inv
           # The invitation's school is the tenant, not the scope's current school.
           |> Ash.Changeset.for_update(:accept, %{}, scope: scope, tenant: inv.workspace_id)
           |> Ash.update() do
      _ = notify_member_joined(user, inv)
      {:ok, inv.workspace}
    else
      {:error, :not_found} -> {:error, :invalid}
      other -> other
    end
  end

  def accept_invitation(%Scope{}, _token), do: {:error, :invalid}

  # The admins hear of the newcomer; a failure here must not undo the acceptance.
  defp notify_member_joined(user, inv) do
    with {:ok, scope} <- TeacherAssistant.Accounts.Workspaces.scope_for(user, inv.workspace_id) do
      TeacherAssistant.Notifications.deliver(
        scope,
        :member_joined,
        TeacherAssistant.Notifications.admin_ids(scope) -- [user.id],
        %{
          name: User.display_name(user),
          roles: Enum.map_join(inv.roles, ",", &to_string/1)
        },
        "/school/members"
      )
    end
  rescue
    error ->
      require Logger
      Logger.warning("member_joined notification failed: #{Exception.message(error)}")
      :error
  end

  defp check_acceptable(%SchoolInvitation{status: :pending} = inv) do
    cond do
      inv.expires_at && DateTime.compare(DateTime.utc_now(), inv.expires_at) == :gt ->
        {:error, :expired}

      true ->
        :ok
    end
  end

  defp check_acceptable(_), do: {:error, :invalid}

  defp check_email(%SchoolInvitation{email: email}, %User{email: user_email}) do
    if to_string(email) == to_string(user_email), do: :ok, else: {:error, :email_mismatch}
  end

  defp active_member_email?(%Scope{} = scope, email) do
    scope
    |> list_members()
    |> Enum.any?(fn m -> m.user.email && to_string(m.user.email) == to_string(email) end)
  end

  # --- Phone accounts (spec 2026-10-07) ---------------------------------------

  @doc """
  Adds a person to the current school by phone. A new number gets an account
  with a temporary password (returned once); a number that already has an
  account is linked without touching it (`temporary_password: nil`).
  """
  def add_member_by_phone(%Scope{} = scope, %{} = attrs, retries \\ 1) do
    with true <- can_manage_staff?(scope) || {:error, :forbidden},
         {:ok, phone} <- normalize_phone(attrs[:phone]),
         :ok <- ensure_not_member(scope, phone) do
      roles = attrs[:roles] || [:teacher]
      status = attrs[:membership_status]

      TeacherAssistant.Repo.transaction(fn ->
        case find_user_by_phone(phone) do
          %User{} = user -> link_user(scope, user, roles, status)
          nil -> create_and_link(scope, attrs[:name], phone, roles, status)
        end
        |> case do
          {:ok, result} -> result
          {:error, error} -> TeacherAssistant.Repo.rollback(error)
        end
      end)
      |> case do
        # Another head created the same number between our lookup and insert.
        {:error, error} when retries > 0 ->
          if phone_taken?(error),
            do: add_member_by_phone(scope, attrs, retries - 1),
            else: {:error, error}

        other ->
          other
      end
    end
  end

  defp normalize_phone(value) do
    case Phone.normalize(value) do
      {:ok, phone} -> {:ok, phone}
      {:error, :invalid} -> {:error, :invalid_phone}
    end
  end

  defp ensure_not_member(scope, phone) do
    if scope |> list_members() |> Enum.any?(&(&1.user.phone == phone)),
      do: {:error, :already_member},
      else: :ok
  end

  # System lookup: the head cannot read users outside their school, but must
  # know whether the number already has an account in order to link it.
  defp find_user_by_phone(phone) do
    User
    |> Ash.Query.filter(phone == ^phone)
    |> Ash.read_one!(authorize?: false)
  end

  defp link_user(scope, user, roles, status) do
    with :ok <- Memberships.ensure_active(user.id, roles, status, scope: scope) do
      {:ok, %{user: user, temporary_password: nil}}
    end
  end

  defp create_and_link(scope, name, phone, roles, status) do
    with {:ok, user} <-
           User
           |> Ash.Changeset.for_create(
             :create_by_school,
             %{name: name, phone: phone, created_in_workspace_id: scope.current_workspace.id},
             scope: scope
           )
           |> Ash.create(),
         :ok <- Memberships.ensure_active(user.id, roles, status, scope: scope) do
      {:ok, %{user: user, temporary_password: user.__metadata__.temporary_password}}
    end
  end

  @doc "New temporary password for a member of the scope's school (operator console spec §3); signs them out everywhere."
  def reset_member_password(%Scope{} = scope, %SchoolMembership{} = membership) do
    with {:ok, %{user: user}} <- Ash.load(membership, :user, scope: scope),
         {:ok, user} <-
           user
           |> Ash.Changeset.for_update(:reset_temporary_password, %{}, scope: scope)
           |> Ash.update(),
         :ok <- revoke_all_sessions(user) do
      {:ok, user.__metadata__.temporary_password}
    end
  end

  @doc """
  New temporary password for any account but an operator's, by the operator (operator
  console spec §3); signs the person out everywhere. Returns the clear password once.

  Journaled under `workspace_id` (the school page the operator acts from), else the
  person's only active school, else no school — never the operator's own session
  school, which is unrelated.
  """
  def operator_reset_password(%Scope{} = scope, %User{} = user, workspace_id \\ nil) do
    workspace_id = workspace_id || only_active_school(user)

    with {:ok, user} <-
           user
           |> Ash.Changeset.for_update(:reset_temporary_password, %{},
             actor: scope.current_user,
             context: %{audit_workspace_id: workspace_id}
           )
           |> Ash.update(),
         :ok <- revoke_all_sessions(user) do
      {:ok, user.__metadata__.temporary_password}
    end
  end

  defp only_active_school(%User{id: user_id}) do
    SchoolMembership
    |> Ash.Query.for_read(:active_for_user, %{user_id: user_id})
    |> Ash.read!(authorize?: false)
    |> case do
      [%{workspace_id: id}] -> id
      _ -> nil
    end
  end

  def can_reset_member_password?(%Scope{} = scope, %User{} = user),
    do: Ash.can?({user, :reset_temporary_password}, scope)

  @doc """
  The ids of the active `members` (from `list_members/1`, users loaded) whose password
  the scope may reset: `can_reset_member_password?/2` for the whole list in a fixed
  number of reads, for showing the button. The `:reset_temporary_password` policy stays
  the authority when a reset runs; a test keeps the two in step.
  """
  def resettable_member_ids(%Scope{current_user: %User{role: :admin}}, members),
    do: for(m <- members, m.user.role != :admin, into: MapSet.new(), do: m.id)

  def resettable_member_ids(
        %Scope{current_user: %User{} = actor, current_workspace: %{id: ws_id}},
        members
      ) do
    if Checks.SchoolRole.holds?(actor, ws_id, :head) do
      verified? = Checks.SchoolVerified.verified?(ws_id)
      elsewhere = active_elsewhere(Enum.map(members, & &1.user_id), ws_id)

      # The policy's order: never an operator, never yourself, never someone active in
      # another school, never a head, never (unverified school) an account it didn't
      # create; the head of the acting school resets its other active members.
      for m <- members,
          m.user.role != :admin,
          m.user_id != actor.id,
          not MapSet.member?(elsewhere, m.user_id),
          :head not in m.roles,
          verified? or m.user.created_in_workspace_id == ws_id,
          into: MapSet.new(),
          do: m.id
    else
      MapSet.new()
    end
  end

  def resettable_member_ids(_scope, _members), do: MapSet.new()

  @doc """
  Corrects a member's name (the school's head, `User`'s `:rename_by_school` policy).
  Spaces are tidied; a blank name is refused. Journaled with the old and new name.
  """
  def rename_member(%Scope{} = scope, %SchoolMembership{user: %User{} = user}, name)
      when is_binary(name) do
    user
    |> Ash.Changeset.for_update(:rename_by_school, %{name: Enum.join(String.split(name), " ")},
      scope: scope
    )
    |> Ash.update()
  end

  def can_rename_member?(%Scope{} = scope, %User{} = user),
    do: Ash.can?({user, :rename_by_school}, scope)

  @doc """
  The ids of the `members` (from `list_members/1`, users loaded) whose name the scope
  may correct, without a read per member. The `:rename_by_school` policy stays the
  authority when a rename runs; a test keeps the two in step.
  """
  def renamable_member_ids(%Scope{current_user: %User{role: :admin}}, members),
    do: for(m <- members, m.user.role != :admin, into: MapSet.new(), do: m.id)

  def renamable_member_ids(
        %Scope{current_user: %User{} = actor, current_workspace: %{id: ws_id}},
        members
      ) do
    if Checks.SchoolRole.holds?(actor, ws_id, :head) do
      verified? = Checks.SchoolVerified.verified?(ws_id)

      for m <- members,
          m.user.role != :admin,
          verified? or m.user.created_in_workspace_id == ws_id,
          into: MapSet.new(),
          do: m.id
    else
      MapSet.new()
    end
  end

  def renamable_member_ids(_scope, _members), do: MapSet.new()

  # Users among `user_ids` with an active membership in a school other than `ws_id`.
  # Check-style read (no tenant, `authorize?: false`), as `Checks.ActiveInAnotherSchool`.
  defp active_elsewhere([], _ws_id), do: MapSet.new()

  defp active_elsewhere(user_ids, ws_id) do
    SchoolMembership
    |> Ash.Query.filter(user_id in ^user_ids and active == true and workspace_id != ^ws_id)
    |> Ash.Query.select([:user_id])
    |> Ash.read!(authorize?: false)
    |> MapSet.new(& &1.user_id)
  end

  @doc """
  The signed-in user deletes their own account (A9): refused with
  `{:error, :has_membership}` while a school counts them as a member; otherwise the
  e-mail, phone, name and password go and every session is signed out.
  """
  def delete_own_account(%Scope{current_user: %User{} = user}) do
    user
    |> Ash.Changeset.for_update(:delete_own_account, %{}, actor: user)
    |> Ash.update()
    |> case do
      {:ok, deleted} ->
        _ = revoke_all_sessions(deleted)
        :ok

      {:error, %Ash.Error.Invalid{} = error} ->
        if Enum.any?(error.errors, &match?(%{field: :id}, &1)),
          do: {:error, :has_membership},
          else: {:error, error}

      {:error, error} ->
        {:error, error}
    end
  end

  @doc """
  Revokes every stored token of the user (sign out on every device). With
  `except_page:` (a LiveView's `socket.transport_pid`), that page stays connected
  so it can send the person to sign in again itself.
  """
  def revoke_all_sessions(%User{} = user, opts \\ []) do
    TeacherAssistant.Accounts.Token
    |> Ash.bulk_update(
      :revoke_all_stored_for_subject,
      %{subject: AshAuthentication.user_to_subject(user)},
      context: %{private: %{ash_authentication?: true}},
      strategy: [:atomic, :atomic_batches, :stream],
      return_errors?: true
    )
    |> case do
      %{status: :success} -> disconnect_live_pages(user, opts[:except_page])
      %{errors: errors} -> {:error, errors}
    end
  end

  def temporary_password_expired?(%User{
        must_change_password: true,
        temporary_password_expires_at: %DateTime{} = at
      }),
      do: DateTime.compare(DateTime.utc_now(), at) == :gt

  def temporary_password_expired?(_user), do: false

  defp gen_token, do: 24 |> :crypto.strong_rand_bytes() |> Base.url_encode64(padding: false)

  # --- Statutory service (spec J2) ------------------------------------------------

  def update_school_service(%Scope{} = scope, value) do
    with {:ok, hours} <- parse_hours(value),
         {:ok, profile} <- fetch_school_profile(scope) do
      update_school_profile(profile, %{statutory_hours: hours}, scope: scope)
    end
  end

  def set_member_service(%Scope{} = scope, %SchoolMembership{} = m, value) do
    with {:ok, hours} <- parse_optional_hours(value) do
      m
      |> Ash.Changeset.for_update(:set_statutory_hours, %{statutory_hours: hours}, scope: scope)
      |> Ash.update()
    end
  end

  def can_set_member_service?(scope),
    do: Ash.can?({SchoolMembership, :set_statutory_hours}, scope)

  defp parse_optional_hours(value) when value in [nil, ""], do: {:ok, nil}
  defp parse_optional_hours(value), do: parse_hours(value)

  defp parse_hours(value) when is_binary(value) do
    case Integer.parse(String.trim(value)) do
      {n, ""} when n in 1..40 -> {:ok, n}
      _ -> {:error, :invalid_hours}
    end
  end

  defp parse_hours(_), do: {:error, :invalid_hours}
end
