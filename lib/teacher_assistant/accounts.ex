  require Ash.Query

  resources do
    resource TeacherAssistant.Accounts.Token

    resource User do
      define :create_user, action: :register_with_password
      define :promote_to_admin
    end

    resource SchoolMembership
    resource TeacherAssistant.Accounts.Notification
    resource TeacherAssistant.Accounts.AuditEvent

    resource SchoolInvitation do
      define :revoke_invitation, action: :revoke
    end

    resource SchoolProfile do
      define :update_school_profile, action: :update
      define :set_school_logo, action: :set_logo, args: [:logo_path]
      define :verify_school, action: :verify, args: [:verified_by_user_id]
      define :reject_school, action: :reject, args: [:verified_by_user_id, :rejection_reason]
    end
  end

  authorization do
    authorize :by_default
  end

  @doc "Stamps `user`'s `last_sign_in_at` (a successful sign-in, as the user)."
  def record_sign_in(%User{} = user) do
    user
    |> Ash.Changeset.for_update(:record_sign_in, %{}, actor: user)
    |> Ash.update()
  end

  @doc "Whether an Ash error is the `:unique_phone` identity violation."
  def phone_taken?(%Ash.Error.Invalid{errors: errors}),
    do: Enum.any?(errors, &match?(%{field: :phone}, &1))

  def phone_taken?(_error), do: false

  @doc "Whether the scope may invite and manage staff (head)."
  def can_manage_staff?(scope), do: Ash.can?({SchoolInvitation, :create}, scope)

  @doc "Whether the scope may edit the school profile and logo (admin axis)."
  def can_edit_profile?(scope, %SchoolProfile{} = profile),
    do: Ash.can?({profile, :update}, scope)

  def can_edit_profile?(_scope, nil), do: false

  # `create_user/1` and `promote_to_admin/1` are generated by the
  # `code_interface` defines on the `User` resource above.
  @doc """
  The id under which every live page of `user` is connected (the session's
  `live_socket_id`, put there at sign-in): revoking their sessions
  disconnects them all, and on reconnecting they meet the sign-in check.
  """
  def live_socket_id(%User{id: id}), do: "users_socket:#{id}"

  @doc """
  Disconnects every live page `user` has open (see `live_socket_id/1`), but the
  one served by `except` (a LiveView's `socket.transport_pid`), if given.
  """
  def disconnect_live_pages(user, except \\ nil)

  def disconnect_live_pages(%User{} = user, nil),
    do: TeacherAssistantWeb.Endpoint.broadcast(live_socket_id(user), "disconnect", %{})

  def disconnect_live_pages(%User{} = user, except) when is_pid(except),
    do:
      TeacherAssistantWeb.Endpoint.broadcast_from(except, live_socket_id(user), "disconnect", %{})

